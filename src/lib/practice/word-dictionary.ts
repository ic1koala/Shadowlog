/**
 * Normalizes a raw word by stripping leading/trailing punctuation and lowercasing.
 */
export function cleanWord(rawWord: string): string {
  if (!rawWord) return "";
  // Strip common punctuation around words: .,!?:;"'()[]{}/*#
  return rawWord
    .replace(/^[^a-zA-Z0-9]+/, "")
    .replace(/[^a-zA-Z0-9]+$/, "")
    .toLowerCase()
    .trim();
}

/**
 * Generates candidate stem variations for an English word.
 */
export function getCandidateStems(word: string): string[] {
  const candidates: string[] = [word];

  // 1. Plurals & Verb endings (-ies -> -y)
  if (word.endsWith("ies") && word.length > 4) {
    candidates.push(word.slice(0, -3) + "y");
  }

  // 2. Plurals & Verb endings (-es -> base or -e)
  if (word.endsWith("es") && word.length > 3) {
    candidates.push(word.slice(0, -2)); // e.g. watches -> watch, boxes -> box
    candidates.push(word.slice(0, -1)); // e.g. places -> place
  }

  // 3. Regular plurals & 3rd person singular (-s)
  if (word.endsWith("s") && !word.endsWith("ss") && word.length > 2) {
    candidates.push(word.slice(0, -1)); // e.g. loops -> loop, servers -> server
  }

  // 4. Past tense & participles (-ied -> -y)
  if (word.endsWith("ied") && word.length > 4) {
    candidates.push(word.slice(0, -3) + "y"); // e.g. applied -> apply
  }

  // 5. Past tense & participles (-ed -> base or -e)
  if (word.endsWith("ed") && word.length > 3) {
    candidates.push(word.slice(0, -1)); // e.g. optimized -> optimize, reduced -> reduce
    candidates.push(word.slice(0, -2)); // e.g. tracked -> track, started -> start
    // Double consonant rule (e.g. stopped -> stop, planned -> plan)
    if (word.length > 5 && word[word.length - 3] === word[word.length - 4]) {
      candidates.push(word.slice(0, -3));
    }
  }

  // 6. Gerunds / present participles (-ing -> base or -e)
  if (word.endsWith("ing") && word.length > 4) {
    candidates.push(word.slice(0, -3)); // e.g. doing -> do, testing -> test
    candidates.push(word.slice(0, -3) + "e"); // e.g. optimizing -> optimize, making -> make
    // Double consonant rule (e.g. running -> run, stopping -> stop)
    if (word.length > 6 && word[word.length - 4] === word[word.length - 5]) {
      candidates.push(word.slice(0, -4));
    }
  }

  // 7. Adverbs (-ly -> base)
  if (word.endsWith("ly") && word.length > 3) {
    candidates.push(word.slice(0, -2)); // e.g. quickly -> quick, significantly -> significant
    if (word.endsWith("ily")) {
      candidates.push(word.slice(0, -3) + "y"); // e.g. easily -> easy
    }
  }

  // 8. Comparatives & Superlatives (-er, -est)
  if (word.endsWith("er") && word.length > 3) {
    candidates.push(word.slice(0, -2)); // e.g. faster -> fast
    candidates.push(word.slice(0, -1)); // e.g. larger -> large
  }
  if (word.endsWith("est") && word.length > 4) {
    candidates.push(word.slice(0, -3)); // e.g. fastest -> fast
    candidates.push(word.slice(0, -2)); // e.g. largest -> large
  }

  return Array.from(new Set(candidates));
}

