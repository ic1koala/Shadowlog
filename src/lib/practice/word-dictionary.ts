/**
 * Synchronous dictionary lookup.
 * Returns the Japanese translation in 0ms.
 * Fallbacks to the cleaned word with brackets if not found in static dictionary.
 */
export function getWordTranslation(rawWord: string): string {
  const cleaned = cleanWord(rawWord);
  if (!cleaned) return rawWord;

  // 1. Check in-memory dynamic cache first
  if (dynamicTranslationCache.has(cleaned)) {
    return dynamicTranslationCache.get(cleaned)!;
  }

  // 2. Exact match in static dictionary
  if (DICTIONARY[cleaned]) {
    return DICTIONARY[cleaned];
  }

  // 3. Candidate stems matching (plurals, verb tenses, participles, adverbs)
  const stems = getCandidateStems(cleaned);
  for (const stem of stems) {
    if (DICTIONARY[stem]) {
      return DICTIONARY[stem];
    }
  }

  // 4. Check if it's pure number
  if (/^\d+$/.test(cleaned)) {
    return cleaned;
  }

  // Fallback: return cleaned word in brackets so it gracefully displays
  return `訳: ${cleaned}`;
}

/**
 * Asynchronously fetches a refined contextual translation for words not in the static dictionary.
 * Caches the result in memory so subsequent views are 0ms.
 */
export async function fetchWordTranslationAsync(
  rawWord: string,
  contextSentence?: string
): Promise<string> {
  const cleaned = cleanWord(rawWord);
  if (!cleaned) return rawWord;

  if (dynamicTranslationCache.has(cleaned)) {
    return dynamicTranslationCache.get(cleaned)!;
  }

  // Check static dictionary first
  const staticResult = getWordTranslation(rawWord);
  if (!staticResult.startsWith("訳: ")) {
    dynamicTranslationCache.set(cleaned, staticResult);
    return staticResult;
  }

  try {
    const res = await fetch("/api/translate-word", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ word: cleaned, sentence: contextSentence }),
    });

    if (res.ok) {
      const data = await res.json();
      if (data?.translation && typeof data.translation === "string") {
        const trans = data.translation.trim();
        dynamicTranslationCache.set(cleaned, trans);
        return trans;
      }
    }
  } catch {
    // Silent failure on network issues; fallback to staticResult
  }

  return staticResult;
}
